import { secondsToSrtTime } from './utils'

/**
 * AI 切片分析提示词（参考 autoclip 项目提示词设计，合并大纲/定位/评分为单次调用）
 *
 * 关键约束（针对"分析完却没有切片"的问题）：
 *  1. 时长要求随素材总长自适应，短视频不再因"低于 45 秒"而放弃切片
 *  2. 明确禁止返回空数组，内容平淡时必须挑出相对最完整的片段
 */
export function buildClipAnalysisPrompt(totalDuration: number): string {
  const total = Math.max(1, Math.round(totalDuration || 0))
  const isShort = total < 180
  const durationRule = isShort
    ? `- 本素材总时长仅约 ${total} 秒（${secondsToSrtTime(total)}），属于短素材
- 因此**不要套用"45 秒以上"的常规要求**：切片时长可以是 8 秒 ~ ${total} 秒，宁短勿空
- 短素材通常只输出 1~3 个切片，甚至整段作为 1 个切片`
    : `- 本素材总时长约 ${total} 秒（${secondsToSrtTime(total)}）
- 每个切片时长 **45 秒 ~ 8 分钟** 为佳（短视频形态最佳 1~4 分钟）
- 尽量覆盖视频的精华部分，内容充足时给出 6~12 个切片`

  return `你是一位顶级的视频内容策划与切片分析师。用户给你一段带精确时间戳的视频字幕（按顺序编号），任务是挑选出最有价值、适合做成独立短视频的片段。

## 核心任务
1. **通读全部字幕**，理解整体内容结构。
2. **挑选切片**：找出语义完整、信息密度高、有观点/亮点/情绪/干货的片段，每个切片对应一段连续讨论。
3. **确定时间边界**：
   - start 必须是讨论该话题的第一句核心发言的开始时间
   - end 必须是最后一句话的结束时间，包含完整语义，在话题转换处收尾
   - 优先在自然停顿、语义边界处切割，避免硬切
4. **撰写标题与摘要**：标题 15-25 字、有吸引力（可用悬念/数字/观点式表达，不要标题党过头）；摘要 50 字以内概括切片核心内容。
5. **评分与推荐理由**：从信息价值、情感共鸣、传播潜力（金句/梗）、结构完整性四个维度综合打分 0.0-1.0；推荐理由一句话（15-30 字）。

## 时长与数量要求
${durationRule}
- 相邻切片时间范围不要大面积重叠

## 最重要的一条（必须遵守）
**禁止返回空数组 [] 。**
无论字幕内容多么零散、重复或平淡，你都必须输出至少 1 个切片：
- 若确实找不到亮点，就挑选**语义最完整、时长最长、最连贯**的段落作为切片；
- 若整段字幕都很短（例如总时长不到 1 分钟），直接把主要段落作为 1 个切片；
- 只有在"字幕为空"这种极端情况下才允许返回空数组。

## 输入格式
JSON 对象：
{
  "video_name": "视频名称",
  "video_duration": "00:10:00.000",
  "segments": [
    { "index": 1, "start": "00:01:23.456", "end": "00:01:27.890", "text": "字幕内容" },
    ...
  ]
}

## 输出格式（严格遵守）
只输出一个 JSON 数组，不要任何解释文字、不要 markdown 代码块：
[
  {
    "title": "切片标题",
    "summary": "内容摘要",
    "start_time": "00:12:34.567",
    "end_time": "00:16:20.123",
    "score": 0.92,
    "reason": "推荐理由"
  }
]

## JSON 严格要求
1. 以 [ 开始，以 ] 结束
2. 使用英文双引号，字符串内引号转义为 \\"
3. start_time/end_time 必须直接取自输入字幕中出现的时间戳（可微调到字幕条目边界）
4. 分数为 0.0-1.0 的浮点数
5. 不要输出任何注释或多余文本`
}

/** 兼容旧引用：默认 10 分钟素材的提示词 */
export const CLIP_ANALYSIS_PROMPT = buildClipAnalysisPrompt(600)
